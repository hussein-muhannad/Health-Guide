// ==========================================
// DISEASE DETAIL PAGE TRANSLATION
// ==========================================

function translateDiseasePage(language) {

    const diseasePage =
        document.querySelector(".organ-page");

    if (!diseasePage) return;


    const path =
        window.location.pathname.toLowerCase();

    const fileName =
        path.substring(path.lastIndexOf("/") + 1);


    const diseaseInfo =
        diseaseData[fileName];

    if (!diseaseInfo) return;


    const backButton =
        document.querySelector(".back-button");

    const diseaseTitle =
        document.querySelector(".organ-header h1");

    const infoCards =
        document.querySelectorAll(
            ".organ-page .info-grid .info-card"
        );

    const headings =
        document.querySelectorAll(
            ".organ-page .info-grid .info-card h2"
        );

    const paragraphs =
        document.querySelectorAll(
            ".organ-page .info-grid .info-card p"
        );

    const sourceCard =
        document.querySelector(".sources-card");

    const sourceHeading =
        sourceCard
            ? sourceCard.querySelector("h2")
            : null;

    const sourceParagraphs =
        sourceCard
            ? sourceCard.querySelectorAll("p")
            : [];


    // ==========================================
    // SAVE ORIGINAL ENGLISH
    // ==========================================

    if (!diseasePage.dataset.englishSaved) {

        diseasePage.dataset.englishSaved = "true";

        diseasePage.dataset.englishTitle =
            diseaseTitle
                ? diseaseTitle.textContent.trim()
                : "";

        diseasePage._englishHeadings =
            Array.from(headings).map(function (item) {
                return item.textContent;
            });

        diseasePage._englishParagraphs =
            Array.from(paragraphs).map(function (item) {
                return item.textContent;
            });

        diseasePage.dataset.englishSourceHeading =
            sourceHeading
                ? sourceHeading.textContent
                : "";

        diseasePage._englishSources =
            Array.from(sourceParagraphs).map(function (item) {
                return item.textContent;
            });
    }


    // ==========================================
    // BACK BUTTON
    // ==========================================

    if (backButton) {

        backButton.textContent =
            language === "ar"
                ? "← العودة إلى الأمراض"
                : "← Back to Diseases";
    }


    // ==========================================
    // ENGLISH
    // ==========================================

    if (language === "en") {

        if (diseaseTitle) {

            diseaseTitle.textContent =
                diseasePage.dataset.englishTitle;
        }


        headings.forEach(function (heading, index) {

            if (diseasePage._englishHeadings[index]) {

                heading.textContent =
                    diseasePage._englishHeadings[index];
            }
        });


        paragraphs.forEach(function (paragraph, index) {

            if (diseasePage._englishParagraphs[index]) {

                paragraph.textContent =
                    diseasePage._englishParagraphs[index];
            }
        });


        if (sourceHeading) {

            sourceHeading.textContent =
                diseasePage.dataset.englishSourceHeading;
        }


        sourceParagraphs.forEach(function (paragraph, index) {

            if (diseasePage._englishSources[index]) {

                paragraph.textContent =
                    diseasePage._englishSources[index];
            }
        });


        return;
    }


    // ==========================================
    // ARABIC
    // ==========================================

    if (language === "ar") {

        if (diseaseTitle) {

            diseaseTitle.textContent =
                diseaseInfo.title;
        }


        headings.forEach(function (heading, index) {

            if (diseaseInfo.headings[index]) {

                heading.textContent =
                    diseaseInfo.headings[index];
            }
        });


        paragraphs.forEach(function (paragraph, index) {

            if (diseaseInfo.paragraphs[index]) {

                paragraph.textContent =
                    diseaseInfo.paragraphs[index];
            }
        });


        if (sourceHeading) {

            sourceHeading.textContent =
                "المصادر الموثوقة";
        }


        sourceParagraphs.forEach(function (paragraph, index) {

            if (diseaseInfo.sources[index]) {

                paragraph.textContent =
                    diseaseInfo.sources[index];
            }
        });
    }

}
